// ── normalisation for the offline rules ──
const PREFIX = '(و|ف)?(عال|بال|لل|ال|ب|ل|ع)?';
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
let RULES = null;
function rules() {
  if (RULES) return RULES;
  const pairs = [];
  for (const rows of Object.values(LEXICON)) for (const [variants, , to] of rows) {
    if (!to) continue;
    const canon = norm(to);
    for (const v of variants.split('|')) { const n = norm(v); if (n && n !== canon) pairs.push([n, canon]); }
  }
  pairs.sort((a, b) => b[0].length - a[0].length); // longest phrase first
  RULES = pairs.map(([from, to]) => {
    const multi = from.includes(' ');
    // single words may carry و/ب/ال/عال… in front; phrases only و
    const re = new RegExp(`(^|[\\s،,؟?!.])${multi ? '(و)?()' : PREFIX}${esc(from)}(?=$|[\\s،,؟?!.])`, 'g');
    return { from, to, re, multi };
  });
  return RULES;
}
const MONTH_WORD = new RegExp(`(^|\\s)(ب)?شهر\\s+(${Object.keys(NUMBERS).filter((k) => NUMBERS[k] >= 1 && NUMBERS[k] <= 12 && Number.isInteger(NUMBERS[k])).join('|')})(?=$|[\\s؟?!.،])`, 'g');
const MONTH_ORD = new RegExp(`(^|\\s)(ب)?الشهر\\s+(${Object.keys(ORDINAL_MONTH).sort((a, b) => b.length - a.length).join('|')})(?=$|[\\s؟?!.،])`, 'g');

// «جم بعت هسع بالامبيرات؟» → «شكد بعت هسه بالمولده؟» (normalised Arabic; customer names are left alone)
export function normalizeIraqi(text) {
  let t = ' ' + norm(text) + ' ';
  for (let pass = 0; pass < 2; pass++) {
    for (const r of rules()) {
      if (!t.includes(r.from)) continue;
      t = t.replace(r.re, (m, b, w, p) => {
        // «ال» + a canonical word that already starts with «ال» → keep one
        const pre = r.to.startsWith('ال') ? (p || '').replace(/ال$/, '').replace(/لل$/, 'ل') : (p || '');
        return b + (w || '') + pre + r.to;
      });
    }
  }
  t = t.replace(MONTH_ORD, (m, b, bi, w) => `${b}${bi || ''}شهر ${ORDINAL_MONTH[w]}`);
  t = t.replace(MONTH_WORD, (m, b, bi, w) => `${b}${bi || ''}شهر ${NUMBERS[w]}`);
  return t.replace(/\s+/g, ' ').trim();
}

// ── for the model prompts: compact «variant/variant = meaning» lines ──
// the model already knows everyday Iraqi words; the prompt carries the shop and money slang (~1.5k tokens)
const PROMPT_CATS = ['question', 'time', 'money', 'wallet', 'debts', 'sales', 'profit', 'expenses', 'position', 'stock', 'order', 'remind', 'forecast', 'anomalies', 'top'];
export const AGENT_CATS = ['time', 'money', 'debts', 'expenses', 'forecast', 'sales', 'profit'];
export function dialectGlossary({ cats = PROMPT_CATS, perEntry = 3, maxChars = 4500 } = {}) {
  const lines = [];
  for (const c of cats) for (const [variants, meaning] of LEXICON[c] || []) lines.push(`${variants.split('|').slice(0, perEntry).join('/')}=${meaning}`);
  let out = '';
  for (const l of lines) { if (out.length + l.length + 2 > maxChars) break; out += (out ? '؛ ' : '') + l; }
  return 'معجم اللهجة العراقية (الكلمة=معناها): ' + out;
}

